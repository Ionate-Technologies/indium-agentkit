#!/usr/bin/env python3
"""Generate ARCHITECTURE.md: the distribution pipeline and subagent roles.

The diagram shows how content flows from this repository to agent tools, and
groups subagents by whether they are read-only or write-scoped (derived from
their declared tools). CATALOG.md remains the full inventory.

Usage:
    python scripts/generate_mermaid_architecture.py [--repo-root PATH] [--out-file ARCHITECTURE.md] [--stdout]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from install import INTERNAL_ITEMS
from validate_content import is_write_scoped, parse_frontmatter


def first_sentence(text: str) -> str:
    match = re.match(r"(.+?[.!?])(?:\s|$)", text.strip())
    return (match.group(1) if match else text.strip()).replace("|", "\\|")


def collect_agents(root: Path) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    read_only: list[tuple[str, str]] = []
    write_scoped: list[tuple[str, str]] = []
    for path in sorted((root / "agents").glob("*.md")):
        fields, _ = parse_frontmatter(path)
        entry = (fields.get("name", path.stem), first_sentence(fields.get("description", "")))
        (write_scoped if is_write_scoped(fields.get("tools", "")) else read_only).append(entry)
    return read_only, write_scoped


def count_skills(root: Path) -> tuple[int, int]:
    names = [path.parent.name for path in (root / "skills").glob("*/SKILL.md")]
    internal = sum(1 for name in names if name in INTERNAL_ITEMS)
    return len(names) - internal, internal


def node_list(names: list[str], prefix: str) -> list[str]:
    return [f'        {prefix}_{name.replace("-", "_")}["{name}"]' for name in names]


def generate(root: Path) -> str:
    read_only, write_scoped = collect_agents(root)
    skills, internal_skills = count_skills(root)
    lines = [
        "# Architecture",
        "",
        "Generated by `python scripts/generate_mermaid_architecture.py`. See",
        "`CATALOG.md` for every skill and subagent with its description.",
        "",
        "## Distribution and validation",
        "",
        "```mermaid",
        "flowchart LR",
        "    subgraph Source [This repository]",
        f'        SKILLS["skills/ ({skills} distributed, {internal_skills} internal)"]',
        f'        AGENTS["agents/ ({len(read_only)} read-only, {len(write_scoped)} write-scoped)"]',
        '        TEMPLATE["templates/AGENTS.md"]',
        "    end",
        "    subgraph Checks [Validation]",
        '        VALIDATE["validate_content.py"]',
        '        HANDOFF["validate_handoff.py"]',
        '        CATALOG["generate_catalog.py / diff_catalog.py"]',
        "    end",
        "    subgraph Install [Installers]",
        '        CLI["npx agentkit (cli.js)"]',
        '        PY["install.py"]',
        '        CURSOR["build_cursor_rules.py"]',
        "    end",
        "    subgraph Targets [Agent tools]",
        '        NATIVE["Claude Code, Codex, Gemini CLI, Antigravity, OpenCode: SKILL.md"]',
        '        SUB["Claude Code, Gemini CLI, Antigravity: subagents"]',
        '        RULES["Cursor: .mdc rules"]',
        '        CONTEXT["AGENTS.md or CLAUDE.md"]',
        "    end",
        "    SKILLS --> VALIDATE",
        "    AGENTS --> VALIDATE",
        "    SKILLS --> CATALOG",
        "    AGENTS --> CATALOG",
        "    CLI --> PY",
        "    SKILLS --> PY",
        "    AGENTS --> PY",
        "    TEMPLATE --> PY",
        "    PY --> NATIVE",
        "    PY --> SUB",
        "    PY --> CURSOR --> RULES",
        "    PY --> CONTEXT",
        "```",
        "",
        "Internal skills apply only to this repository and are left out of the",
        "`install` bundle; install one with `add <name>`.",
        "",
        "## Subagent roles",
        "",
        "Read-only subagents declare `Read, Grep, Glob, Bash` (research roles may add",
        "web tools) and use Bash only for non-mutating commands. Write-scoped",
        "subagents also declare `Edit` and `Write` and change only the paths the",
        "parent assigns. Bash cannot be restricted through frontmatter, so these",
        "limits are enforced by each subagent's instructions and the host's",
        "permission settings.",
        "",
        "```mermaid",
        "flowchart TB",
        "    subgraph ReadOnly [Read-only]",
        *node_list([name for name, _ in read_only], "R"),
        "    end",
        "    subgraph WriteScoped [Write-scoped]",
        *node_list([name for name, _ in write_scoped], "W"),
        "    end",
        "```",
        "",
        "| Role | Subagent | Responsibility |",
        "| --- | --- | --- |",
    ]
    for role, entries in (("write-scoped", write_scoped), ("read-only", read_only)):
        for name, summary in entries:
            lines.append(f"| {role} | `{name}` | {summary} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate ARCHITECTURE.md for indium-agentkit.")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--out-file", default="ARCHITECTURE.md", help="Output path relative to the repository root")
    parser.add_argument("--stdout", action="store_true", help="Print instead of writing the file")
    args = parser.parse_args()

    root = args.repo_root.resolve()
    content = generate(root)
    if args.stdout:
        print(content)
    else:
        out_path = root / args.out_file
        out_path.write_text(content, encoding="utf-8")
        print(f"generated {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
